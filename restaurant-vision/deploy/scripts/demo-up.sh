#!/usr/bin/env bash
# Restaurant Vision Docker demo: Postgres + cloud, seed the demo tenant, then a simulated edge
# paired to the "Tel Aviv" site that plays a dinner service at 20x speed.
#
# Usage: deploy/scripts/demo-up.sh [--no-build] [--speed N] [--scenario PATH] [--site NAME]
#   --no-build       reuse the images built by an earlier run
#   --speed N        simulation speed (default 20: the 2 h demo dinner plays in about 6 min)
#   --scenario PATH  scenario inside the edge image (default simulator/scenarios/demo_dinner.yaml)
#   --site NAME      seeded site to pair with: "Tel Aviv" (default) or "Sydney"
# Re-running restarts the simulation with a fresh pairing code; the database is kept.
# Registry mirror: export RV_PYTHON_IMAGE, RV_NODE_IMAGE, RV_POSTGRES_IMAGE before running.
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
DEPLOY_DIR=$(dirname "$SCRIPT_DIR")
COMPOSE_FILE="$DEPLOY_DIR/docker-compose.yml"
ENV_FILE="$DEPLOY_DIR/.env"
SITE_NAME="Tel Aviv"
BUILD=1

usage() { sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --no-build) BUILD=0 ;;
    --speed) export RV_SIM_SPEED="${2:?--speed needs a value}"; shift ;;
    --scenario) export RV_SCENARIO="${2:?--scenario needs a value}"; shift ;;
    --site) SITE_NAME="${2:?--site needs a value}"; shift ;;
    -h | --help) usage; exit 0 ;;
    *) echo "error: unknown option $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

say() { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }
compose() { docker compose -f "$COMPOSE_FILE" --profile demo "$@"; }

command -v docker >/dev/null || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "the Docker Compose v2 plugin is required (docker compose)"
docker info >/dev/null 2>&1 || die "the Docker daemon is not running"

# Read deploy/.env (if any) so the port variables it may hold apply to the URLs printed below.
if [[ -f "$ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  set +a
fi
CLOUD_PORT="${RV_CLOUD_PORT:-8000}"
EDGE_PORT="${RV_EDGE_PORT:-8787}"

if [[ $BUILD -eq 1 ]]; then
  say "Building images (cloud: API + dashboard + waiter PWA; edge: rv-edge + simulator + YOLOX-tiny)"
  compose build cloud edge-sim
fi

if [[ ! -f "$ENV_FILE" ]]; then
  say "Creating $ENV_FILE with a fresh JWT secret and Web Push (VAPID) keys"
  jwt_secret=$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')
  vapid=$(compose run --rm --no-deps -T cloud python -m rv_cloud.tools.gen_vapid)
  grep -q '^RV_VAPID_PUBLIC_KEY=' <<<"$vapid" || die "could not generate VAPID keys: $vapid"
  (
    umask 077
    {
      echo "# Demo secrets for deploy/docker-compose.yml (generated by demo-up.sh; git-ignored)."
      echo "RV_JWT_SECRET=$jwt_secret"
      echo "$vapid"
    } >"$ENV_FILE"
  )
fi

say "Starting Postgres and the cloud (waits until healthy)"
compose up -d --wait --wait-timeout 240 db cloud

say "Seeding the demo tenant (idempotent; prints fresh pairing codes)"
seed_out=$(compose exec -T cloud python -m rv_cloud.tools.seed_demo)
printf '%s\n' "$seed_out" | sed 's/^/    /'
pair_code=$(printf '%s\n' "$seed_out" | awk -v site="$SITE_NAME" 'index($0, "Site " site " ") == 1 { print $NF }')
[[ -n "$pair_code" ]] || die "no pairing code found for site '$SITE_NAME' in the seed output"

say "Starting the simulated edge for '$SITE_NAME' (pairing code $pair_code)"
RV_PAIR_CODE="$pair_code" compose up -d --no-deps --force-recreate --renew-anon-volumes edge-sim

if command -v curl >/dev/null; then
  for _ in $(seq 1 60); do
    if curl -fsS "http://localhost:$EDGE_PORT/local/health" >/dev/null 2>&1; then
      break
    fi
    if [[ "$(compose ps -a --format '{{.State}}' edge-sim 2>/dev/null)" == "exited" ]]; then
      compose logs --tail 40 edge-sim >&2
      die "the simulated edge exited (logs above)"
    fi
    sleep 1
  done
  curl -fsS "http://localhost:$EDGE_PORT/local/health" >/dev/null 2>&1 \
    || { compose logs --tail 40 edge-sim >&2; die "the simulated edge did not become healthy"; }
fi

cat <<EOF

Restaurant Vision demo is running.

  Dashboard     http://localhost:$CLOUD_PORT/
                owner   demo@example.com    / demo-password-123
                manager manager@example.com / demo-password-123  (Tel Aviv)
  Waiter PWA    http://localhost:$CLOUD_PORT/waiter/
                waiter  waiter@example.com  / demo-password-123  (Tel Aviv)
  API docs      http://localhost:$CLOUD_PORT/api/v1/docs
  Edge LAN API  http://localhost:$EDGE_PORT/local/health    (setup wizard at http://localhost:$EDGE_PORT/ when edge-ui is built)

  Scenario: ${RV_SCENARIO:-simulator/scenarios/demo_dinner.yaml} at speed ${RV_SIM_SPEED:-20}, paired to "$SITE_NAME".
  The demo dinner (2 h) plays in about 6 minutes; run this script again to restart it.

  Edge logs   docker compose -f deploy/docker-compose.yml --profile demo logs -f edge-sim
  Stop        deploy/scripts/demo-down.sh            (--purge also deletes the database)
EOF
