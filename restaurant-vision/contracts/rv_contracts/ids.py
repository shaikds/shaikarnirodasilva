"""UUIDv7 identifiers (RFC 9562), implemented here because Python 3.11 has no ``uuid.uuid7``.

Layout (128 bits, most significant first)::

    48 bits unix_ts_ms | 4 bits version (0b0111) | 12 bits counter
     2 bits variant (0b10) | 62 bits random

The 12-bit ``rand_a`` field is a monotonic counter (RFC 9562 section 6.2, method 1): it starts
at a random value below 2048 each new millisecond and is incremented for every id generated in
the same millisecond. If the wall clock goes backwards, or the counter overflows, the previous
timestamp is reused/advanced by 1 ms, so ids generated by one process are strictly increasing
both as integers and as canonical strings. Ids are therefore time-ordered (good for database
indexes) and serve as idempotency keys.
"""

import secrets
import threading
import time
import uuid

_COUNTER_MAX = 0xFFF
_TS_MASK = (1 << 48) - 1


class _Uuid7Generator:
    """Thread-safe monotonic UUIDv7 generator. ``unix_ms`` is injectable for tests."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._last_ms = -1
        self._counter = 0

    def next(self, unix_ms: int) -> str:
        with self._lock:
            if unix_ms > self._last_ms:
                self._last_ms = unix_ms
                self._counter = secrets.randbits(11)
            else:
                self._counter += 1
                if self._counter > _COUNTER_MAX:
                    self._last_ms += 1
                    self._counter = secrets.randbits(11)
            ts_ms = self._last_ms & _TS_MASK
            counter = self._counter
        value = (
            (ts_ms << 80)
            | (0x7 << 76)
            | (counter << 64)
            | (0b10 << 62)
            | secrets.randbits(62)
        )
        return str(uuid.UUID(int=value))


_generator = _Uuid7Generator()


def new_uuid7() -> str:
    """Return a new canonical lowercase UUIDv7 string, strictly increasing within the process.

    Use it for any generated id: ``alert_id``, ``session_id``, ``command_id`` ...
    """
    return _generator.next(time.time_ns() // 1_000_000)


def new_event_id() -> str:
    """Return a new ``EdgeEvent.event_id`` (UUIDv7, the event's idempotency key)."""
    return new_uuid7()


def uuid7_timestamp(value: str) -> float:
    """Return the creation time embedded in a UUIDv7 string, as Unix epoch seconds."""
    parsed = uuid.UUID(value)
    if parsed.version != 7:
        raise ValueError(f"not a UUIDv7: {value!r}")
    return (parsed.int >> 80) / 1000.0
