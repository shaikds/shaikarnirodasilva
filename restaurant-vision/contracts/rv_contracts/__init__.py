"""Restaurant Vision shared contracts: the single source of truth for data shapes shared by the
edge engine, the cloud backend, the simulator and the web apps (architecture section 5).

Import everything from the package root::

    from rv_contracts import SiteConfig, EdgeEvent, parse_event, make_event, TableState

Modules:

* :mod:`~rv_contracts.geometry`: normalized image geometry and pure helpers.
* :mod:`~rv_contracts.config`: ``SiteConfig`` and its parts (5.1).
* :mod:`~rv_contracts.vision`: hot-path dataclasses and protocols (5.2).
* :mod:`~rv_contracts.events`: ``EdgeEvent`` union (5.3).
* :mod:`~rv_contracts.api`: REST payloads (7.3).
* :mod:`~rv_contracts.ids`: UUIDv7.
* :mod:`~rv_contracts.schema_export`: JSON Schema for TS types.
* :mod:`~rv_contracts.fixtures`: sample config and events for tests (import it explicitly).

Every pydantic model rejects unknown fields and is immutable; see :mod:`rv_contracts._base`.
"""

