/** Get all city names (returns both Hebrew and English) */
export function getCityList(lang: 'he' | 'en' = 'he'): string[] {
  return ISRAEL_LOCATIONS.map(c => lang === 'he' ? c.name_he : c.name);
}

/** Get neighborhoods for a city (by Hebrew or English name) */
export function getNeighborhoods(city: string): string[] {
  const found = ISRAEL_LOCATIONS.find(
    c => c.name === city || c.name_he === city
  );
  return found?.neighborhoods ?? [];
}

/** Find city object by name (EN or HE) */
export function findCity(name: string): IsraelCity | undefined {
  return ISRAEL_LOCATIONS.find(c => c.name === name || c.name_he === name);
}
